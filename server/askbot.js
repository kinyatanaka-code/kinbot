const SYSTEM = `あなたは営業支援システム「kinbot」の案内係です。使う人は営業のメンバーで、開発者ではありません。

答え方の決まり:
- 日本語。短く、やさしく。むずかしい言葉を使わない。
- 操作を聞かれたら「どの画面の、どこを押すか」を順番で書く。
- 【いちばん大事】下の資料に書いていないことは、絶対に作らない。
  分からないときは、正直に「分かりません」と答える。それが正しい答えです。
- 長い説明は避ける。3〜5行が目安。多くても10行。
- 絵文字は使わない。

返事は、次のJSONだけを返してください（前置き・説明・コードフェンスは書かない）:
{
  "answer": "画面に出す返事",
  "note": null もしくは { "kind": "request" | "bug" | "gap", "title": "開発メモに残す一行" }
}

note を付けるのは、次のときだけです:
- 相手が「〜してほしい」と要望を言った → kind: "request"
- 相手が「〜ができない」「おかしい」と言った → kind: "bug"
- 資料に書いておらず、答えられなかった → kind: "gap"
それ以外（ふつうの質問に答えられた）は note: null にしてください。

note を付けたときも、answer には「開発メモに残しました」と書かないでください
（画面に印が出るので、二重になります）。かわりに、いまできる代わりの方法があれば教えてください。`;

// ロボへの問いかけに答える。
// 返すのは { answer, note } の形。noteがあれば、呼び出し側で開発メモに残す。
export async function askBot({ message, history = [], callLLM }) {
  const text = String(message || "").trim();
  if (!text) return { answer: "何を知りたいか、書いてみてください。", note: null };
  if (!callLLM) {
    return {
      answer: "いまAIが使えないので、答えられません。聞かれたことは残しておきます。",
      note: { kind: "gap", title: `ロボに聞かれたが答えられなかった：${text.slice(0, 100)}` },
    };
  }

  const past = (history || []).slice(-6)
    .map((h) => `${h.role === "bot" ? "案内係" : "相手"}：${String(h.text || "").slice(0, 300)}`)
    .join("\n");

  const user =
    `【kinbotの資料】\n${KINBOT_GUIDE}\n\n` +
    (past ? `【これまでのやり取り】\n${past}\n\n` : "") +
    `【相手の言葉】\n${text}\n`;

  try {
    const raw = await callLLM(SYSTEM, user, 900, { json: true });
    let d = typeof raw === "string" ? null : raw;
    if (!d) {
      const cleaned = String(raw || "").replace(/```json|```/g, "").trim();
      try { d = JSON.parse(cleaned); }
      catch {
        const m = cleaned.match(/\{[\s\S]*\}/);
        if (m) { try { d = JSON.parse(m[0]); } catch {} }
      }
    }
    if (!d || !d.answer) throw new Error("読み取れませんでした");
    const note = d.note && d.note.title
      ? {
          kind: ["request", "bug", "gap"].includes(d.note.kind) ? d.note.kind : "request",
          title: String(d.note.title).slice(0, 200),
        }
      : null;
    return { answer: String(d.answer).slice(0, 2000), note };
  } catch (e) {
    // AIが答えられなかったときも、聞かれたことは残す
    return {
      answer: "うまく答えられませんでした。聞かれたことは残しておきます。",
      note: { kind: "gap", title: `ロボに聞かれたが答えられなかった：${text.slice(0, 100)}` },
    };
  }
}
