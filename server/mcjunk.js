// 会社名ではないリードの見分け（2026-11-26 福井さん「テスト山田・ロープレ練習のような企業名ではないリストが混ざっているのでリードから消して」）。
//   ロープレや動作確認のために作った「テスト山田」「ロープレ練習」などが MOCHICALL のリードに入り、かける順番に出ていた。
//   本物の会社を巻き込まないよう、次の2つがそろったときだけ「会社名ではない」とする。
//     ・テスト／ロープレ／練習／ダミー／サンプル／test などの言葉が入っている
//     ・株式会社・有限会社・法人・病院などの「会社や団体だと分かる言葉」が入っていない（「株式会社テストテック」のような本物の会社は残す）
//   消す前には必ず管理者が一覧で確かめる（GET /api/mccall/junk-leads → POST で選んだ分だけ消す）。

const JUNK_WORD = /((?<!コン|プロ)テスト|(?<!ｺﾝ|ﾌﾟﾛ)ﾃｽﾄ|てすと|ロープレ|ﾛｰﾌﾟﾚ|ろーぷれ|ロールプレイ|練習|ダミー|ﾀﾞﾐｰ|サンプル|ｻﾝﾌﾟﾙ|試験用|検証用|\btest\b|\btesting\b|\bdummy\b|\bsample\b|^test|test$)/i;
const ORG_WORD = /(株式会社|有限会社|合同会社|合資会社|合名会社|[（(]\s*[株有同]\s*[）)]|㈱|㈲|法人|組合|協会|連合会|事務所|病院|医院|クリニック|学校|学園|大学|商店|工業|製作所|\binc\b|\bcorp|\bco\.?,?\s*ltd|\bltd\b|\bllc\b|\bk\.?k\.?$)/i;

export function isJunkCompany(name) {
  const s = String(name || "").normalize("NFKC").trim();
  if (!s || s.length > 60) return false;   // 空・長すぎる名前は判断しない（ほかの決まりに任せる）
  return JUNK_WORD.test(s) && !ORG_WORD.test(s);
}
